/**
 * Playlists and channels: one link that means many videos.
 *
 * `isSupportedYouTubeUrl` has always accepted these, and every one of them then
 * resolved to exactly one video - whichever the URL happened to also name, or
 * an error. Dropping a 40-video playlist in and getting one video back is the
 * kind of wrong that looks like the feature working.
 *
 * The URL reading here is pure, and deliberately separate from the yt-dlp call
 * that enumerates entries: what counts as a playlist is a decision worth
 * testing without a network.
 */

/** How many entries one link may turn into. A channel can list thousands. */
export const MAX_PLAYLIST_ENTRIES = 400

export interface PlaylistEntry {
  /** The watch URL Draco will resolve when this entry becomes a download. */
  url: string
  title: string
  /** Seconds, when the flat listing knew; playlists of live items often do not. */
  duration: number | null
}

export interface PlaylistListing {
  title: string
  entries: PlaylistEntry[]
  /** True when the source had more entries than `MAX_PLAYLIST_ENTRIES`. */
  truncated: boolean
}

/**
 * Whether this link stands for a collection rather than a single video.
 *
 * A watch URL carrying `list=` is the ambiguous case, and it is treated as a
 * playlist: the user pasted a link that names one, and the one-video reading is
 * still available by removing it. `RD`-prefixed lists - YouTube's endless
 * autogenerated mixes - are the exception, because they have no last entry.
 */
export function isPlaylistUrl(value: unknown): boolean {
  const parsed = parseYouTubeUrl(value)
  if (!parsed) return false

  const list = parsed.searchParams.get('list')
  if (list) return !isEndlessMix(list)

  return isChannelPath(parsed.pathname)
}

/** A channel link means "everything this person posted", which is a listing too. */
function isChannelPath(pathname: string): boolean {
  return (
    /^\/@[^/]+(?:\/(?:videos|shorts|streams|featured))?\/?$/i.test(pathname) ||
    /^\/(?:channel|c|user)\/[^/]+(?:\/(?:videos|shorts|streams|featured))?\/?$/i.test(pathname) ||
    /^\/playlist\/?$/i.test(pathname)
  )
}

/**
 * A mix has no end: YouTube generates the next entry from what you just
 * watched, so "download the playlist" has no meaning for one.
 */
function isEndlessMix(list: string): boolean {
  return /^(RD|UL|TL)/.test(list)
}

/** The `list=` id, when there is one. Used to name the folder entries land in. */
export function playlistIdOf(value: unknown): string | null {
  const parsed = parseYouTubeUrl(value)
  const list = parsed?.searchParams.get('list')
  return list && !isEndlessMix(list) ? list : null
}

/**
 * The same link with `list=` removed - the single video the user could have
 * meant instead, offered alongside the playlist rather than guessed at.
 */
export function singleVideoUrl(value: string): string | null {
  const parsed = parseYouTubeUrl(value)
  if (!parsed || !parsed.searchParams.get('v')) return null
  parsed.searchParams.delete('list')
  parsed.searchParams.delete('index')
  parsed.searchParams.delete('start_radio')
  return parsed.toString()
}

function parseYouTubeUrl(value: unknown): URL | null {
  if (typeof value !== 'string') return null
  try {
    const url = new URL(value)
    if (url.protocol !== 'https:') return null
    if (!/(^|\.)youtube\.com$/i.test(url.hostname) && !/(^|\.)youtu\.be$/i.test(url.hostname)) return null
    return url
  } catch {
    return null
  }
}

/**
 * Turns yt-dlp's `--flat-playlist` JSON into entries.
 *
 * Flat means yt-dlp lists what is in the playlist without resolving any of it -
 * one quick call instead of one lookup per video. Each entry is resolved later,
 * as its download starts, which is also the only way the signed URLs are still
 * fresh when they are used.
 */
export function parseFlatPlaylist(raw: unknown): PlaylistListing {
  const root = raw as Record<string, unknown> | null
  const rawEntries = Array.isArray(root?.entries) ? root!.entries : []

  const entries: PlaylistEntry[] = []
  for (const item of rawEntries) {
    const entry = item as Record<string, unknown> | null
    if (!entry || typeof entry !== 'object') continue

    const url = watchUrlOf(entry)
    if (!url) continue

    const duration = typeof entry.duration === 'number' && Number.isFinite(entry.duration)
      ? Math.max(0, Math.round(entry.duration))
      : null

    entries.push({
      url,
      title: typeof entry.title === 'string' && entry.title.trim()
        ? entry.title.trim().slice(0, 300)
        : 'Untitled',
      duration
    })

    if (entries.length >= MAX_PLAYLIST_ENTRIES) break
  }

  return {
    title: typeof root?.title === 'string' && root.title.trim()
      ? root.title.trim().slice(0, 200)
      : 'Playlist',
    entries,
    truncated: rawEntries.length > entries.length
  }
}

/**
 * The watch URL for one flat entry.
 *
 * yt-dlp gives a bare id for a YouTube entry and a full URL for some other
 * extractors, and a private or deleted video appears as an entry with neither.
 * Building from the id is preferred: the `url` field of a flat entry is
 * sometimes a shortened form that carries the playlist along with it.
 */
function watchUrlOf(entry: Record<string, unknown>): string | null {
  const id = typeof entry.id === 'string' ? entry.id.trim() : ''
  if (/^[A-Za-z0-9_-]{5,20}$/.test(id)) return `https://www.youtube.com/watch?v=${id}`

  const url = typeof entry.url === 'string' ? entry.url.trim() : ''
  if (/^https:\/\/[^\s]+$/i.test(url) && url.length < 2000) return url

  return null
}
