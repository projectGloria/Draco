"""Generate src/cli/terminal-icon.ts: Draco's icon as terminal pixel art.

The terminal draws it with half-blocks (one cell = two square pixels), so the
art costs one row per two pixels. Its height is pinned to the shortcut box
beside it (`--rows`, default 11 = 9 shortcuts + 2 borders); the width follows
the icon's aspect ratio. A plain downscale of the painted icon is
mush - it is all orange gradients with fine scale detail - so this pipeline:

  1. box-downscales to 4x the target and median-filters, which keeps the big
     shapes (horn, jaw, mane) and drops scale-level texture;
  2. box-downscales to the target and snaps every pixel to a 7-step fire ramp,
     which reads as intentional pixel art instead of noise;
  3. removes lone speckles (a pixel 2+ steps from all four neighbours);
  4. darkens the silhouette edge, so the head separates from any background.

The silhouette itself is never filtered: the flame spikes are what make it read
as a dragon at this size. Run `npm run icon:terminal` after changing icon.png.
"""
from pathlib import Path
from PIL import Image, ImageEnhance, ImageFilter
import argparse
import json

parser = argparse.ArgumentParser()
parser.add_argument('--rows', type=int, default=11, help='terminal rows the art may use (2 pixels each)')
ROWS = parser.parse_args().rows
PALETTE = ['460804', '961406', 'd6340a', 'f46810', 'fca01c', 'ffd448', 'fff4be']
RGB = [tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in PALETTE]


def nearest(colour):
    # Weighted RGB distance (green matters most to the eye) keeps the ramp monotonic.
    return min(range(len(RGB)), key=lambda i: sum((a - b) ** 2 * w for a, b, w in zip(colour, RGB[i], (3, 4, 2))))


root = Path(__file__).resolve().parent.parent
source = Image.open(root / 'resources/icon.png').convert('RGBA')
# Crop to the visible art first, so the target height is spent on the dragon and
# not on transparent margin - otherwise the final size depends on the trim.
source = source.crop(source.split()[3].point(lambda a: 255 if a >= 200 else 0).getbbox())
HEIGHT = ROWS * 2
WIDTH = max(1, round(HEIGHT * source.width / source.height))
mid = source.resize((WIDTH * 4, HEIGHT * 4), Image.Resampling.BOX)
rgb = mid.convert('RGB').filter(ImageFilter.MedianFilter(7)).resize((WIDTH, HEIGHT), Image.Resampling.BOX)
rgb = ImageEnhance.Contrast(rgb).enhance(1.3).load()
alpha = mid.split()[3].resize((WIDTH, HEIGHT), Image.Resampling.BOX).load()

grid = [[nearest(rgb[x, y]) if alpha[x, y] >= 120 else None for x in range(WIDTH)] for y in range(HEIGHT)]


def neighbours(x, y):
    return [(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]


def inside(x, y):
    return 0 <= x < WIDTH and 0 <= y < HEIGHT


for y in range(HEIGHT):
    for x in range(WIDTH):
        value = grid[y][x]
        around = [grid[ny][nx] for nx, ny in neighbours(x, y) if inside(nx, ny) and grid[ny][nx] is not None]
        if value is not None and len(around) == 4 and all(abs(value - n) >= 2 for n in around):
            grid[y][x] = sorted(around)[1]

rows = []
for y in range(HEIGHT):
    row = ''
    for x in range(WIDTH):
        value = grid[y][x]
        if value is None:
            row += '.'
            continue
        edge = any(not inside(nx, ny) or grid[ny][nx] is None for nx, ny in neighbours(x, y))
        row += str(1 if edge and value > 1 else value)
    rows.append(row)

# Trim fully transparent columns so the art sits flush; rows stay as they are,
# because the height is a promise to the layout (it matches the shortcut box).
left = min(len(r) - len(r.lstrip('.')) for r in rows)
right = min(len(r) - len(r.rstrip('.')) for r in rows)
rows = [r[left:len(r) - right] for r in rows]
assert len(rows) == HEIGHT

(root / 'src/cli/terminal-icon.ts').write_text(
    '// Generated by tools/gen-terminal-icon.py from resources/icon.png - do not edit.\n'
    '// One character per pixel: "." is transparent, a digit indexes `palette`.\n'
    f'export const iconPalette: readonly string[] = {json.dumps(PALETTE)}\n\n'
    'export const iconPixels: readonly string[] = [\n'
    + ''.join(f'  {json.dumps(r)},\n' for r in rows)
    + ']\n', encoding='utf-8')
print(f'{len(rows[0])}x{len(rows)} pixels -> {len(rows[0])} columns x {len(rows) // 2} rows')
